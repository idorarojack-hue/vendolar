import React from 'react';
import classNames from 'classnames';
import { observer } from 'mobx-react-lite';
import { DBOT_TABS } from '@/constants/bot-contents';
import { useRunningSessions } from '@/hooks/useAutoTrader';
import { useStore } from '@/hooks/useStore';
import { getAutoTrader, stopAllSessions } from '@/services/vindolar/auto-trader';
import { localize } from '@deriv-com/translations';
import '@/components/vindolar/vindolar.scss';

/** Which tab a session id belongs to (ids are set by each tool). */
const tabForSession = (id: string) => {
    if (id === 'speed-trader') return { tab: DBOT_TABS.SPEED_TRADER, tool: 'Speedbot' };
    if (id === 'recovery-trader') return { tab: DBOT_TABS.RECOVERY_TRADER, tool: 'TickPulse' };
    if (id === 'bulk-trader') return { tab: DBOT_TABS.BULK_TRADER, tool: 'Bulk Trader' };
    if (id === 'market-scanner') return { tab: DBOT_TABS.MARKET_SCANNER, tool: 'Pulse AI Scanner' };
    if (id.startsWith('automated-')) return { tab: DBOT_TABS.AUTOMATED, tool: 'Automated' };
    if (id.startsWith('pattern-')) return { tab: DBOT_TABS.PATTERN_BOTS, tool: 'Premium AI Bots' };
    if (id.startsWith('auto-')) return { tab: DBOT_TABS.AUTO_STRATEGIES, tool: 'Auto Trading' };
    return { tab: DBOT_TABS.DASHBOARD, tool: '' };
};

export const RiskDialog = ({ onClose }: { onClose: () => void }) => {
    const close_ref = React.useRef<HTMLButtonElement>(null);
    React.useEffect(() => {
        close_ref.current?.focus();
        const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
        document.addEventListener('keydown', onKey);
        return () => document.removeEventListener('keydown', onKey);
    }, [onClose]);

    return (
        <div className='vd-dialog__backdrop' onClick={onClose} role='presentation'>
            <div
                className='vd-dialog'
                role='dialog'
                aria-modal='true'
                aria-labelledby='vd-risk-title'
                onClick={e => e.stopPropagation()}
            >
                <h2 id='vd-risk-title'>{localize('Risk disclaimer')}</h2>
                <p>
                    {localize(
                        'Trading options and synthetic indices carries a high level of risk. You can lose all the money you put in, and losses can happen quickly — especially with automated tools that place many trades.'
                    )}
                </p>
                <ul>
                    <li>{localize('Volatility indices are generated by a random number generator. Past digits and prices do not predict the next one.')}</li>
                    <li>{localize('No bot, statistic, signal or strategy on Vindolar can guarantee profit. Names describe how a tool works, not how well it performs.')}</li>
                    <li>{localize('Martingale and other stake-sizing systems increase your stake after losses. They change how you lose, not whether you lose.')}</li>
                    <li>{localize('Always test on your demo account first and set a stop loss you can afford to lose.')}</li>
                    <li>{localize('Trades are executed by Deriv. Vindolar is a tool built on the Deriv API and does not give financial advice.')}</li>
                </ul>
                <button ref={close_ref} type='button' className='vd-primary-button' onClick={onClose}>
                    {localize('I understand')}
                </button>
            </div>
        </div>
    );
};

/** Bottom-left corner: risk disclaimer + running automated sessions (visible on every tab). */
const GlobalStatus = observer(({ has_bot_bar }: { has_bot_bar: boolean }) => {
    const { dashboard, client } = useStore();
    const sessions = useRunningSessions();
    const [show_risk, setShowRisk] = React.useState(false);
    const [show_list, setShowList] = React.useState(false);
    const currency = client.is_logged_in ? client.currency || 'USD' : 'USD';
    const total = sessions.reduce((sum, s) => sum + s.state.profit, 0);

    React.useEffect(() => {
        if (sessions.length === 0) setShowList(false);
    }, [sessions.length]);

    return (
        <div className={classNames('vd-global', { 'vd-global--above-bar': has_bot_bar })}>
            <button type='button' className='vd-global__risk' aria-label={localize('Risk disclaimer')} onClick={() => setShowRisk(true)}>
                <span aria-hidden='true'>⚠</span>
                <span className='vd-global__label'>{localize('Risk disclaimer')}</span>
            </button>

            {sessions.length > 0 && (
                <div className='vd-global__sessions'>
                    <button
                        type='button'
                        className='vd-global__chip'
                        aria-expanded={show_list}
                        onClick={() => setShowList(v => !v)}
                    >
                        <span className='vd-session__dot vd-session__dot--waiting' aria-hidden='true' />
                        <span className='vd-global__label'>
                            {sessions.length === 1
                                ? localize('1 auto session running')
                                : localize('{{n}} auto sessions running', { n: sessions.length })}
                        </span>
                        <span className='vd-global__count' aria-hidden='true'>
                            {sessions.length}
                        </span>
                        <span className={classNames({ 'is-up': total > 0, 'is-down': total < 0 })}>
                            {total > 0 ? '+' : ''}
                            {total.toFixed(2)} {currency}
                        </span>
                    </button>
                    {show_list && (
                        <div className='vd-global__list' role='region' aria-label={localize('Running sessions')}>
                            <ul>
                                {sessions.map(({ id, state }) => {
                                    const { tab, tool } = tabForSession(id);
                                    return (
                                        <li key={id}>
                                            <div>
                                                <strong>{state.strategy_name ?? tool}</strong>
                                                <small>
                                                    {localize(tool)} · {state.wins + state.losses} {localize('trades')} ·{' '}
                                                    <span className={classNames({ 'is-up': state.profit > 0, 'is-down': state.profit < 0 })}>
                                                        {state.profit > 0 ? '+' : ''}
                                                        {state.profit.toFixed(2)} {currency}
                                                    </span>
                                                </small>
                                            </div>
                                            <button
                                                type='button'
                                                className='vd-session__reset'
                                                onClick={() => {
                                                    dashboard.setActiveTab(tab);
                                                    setShowList(false);
                                                }}
                                            >
                                                {localize('Open')}
                                            </button>
                                            <button
                                                type='button'
                                                className='vd-global__stop'
                                                disabled={state.status === 'stopping'}
                                                onClick={() => getAutoTrader(id).stop()}
                                            >
                                                {state.status === 'stopping' ? localize('Stopping…') : localize('Stop')}
                                            </button>
                                        </li>
                                    );
                                })}
                            </ul>
                            {sessions.length > 1 && (
                                <button type='button' className='vd-global__stop vd-global__stop--all' onClick={() => stopAllSessions('Stopped from the sessions list')}>
                                    {localize('Stop all')}
                                </button>
                            )}
                        </div>
                    )}
                </div>
            )}

            {show_risk && <RiskDialog onClose={() => setShowRisk(false)} />}
        </div>
    );
});

export default GlobalStatus;
